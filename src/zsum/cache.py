def save_membership(index, cache_dir: Path) -> None:
    """Save current collection membership to cache for change detection."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    membership = {key: sorted(col.item_citekeys) for key, col in index.collections.items()}
    path = cache_dir / "membership.json"
    with open(path, "w") as f:
        json.dump(membership, f, indent=2)
    logger.info("Saved membership snapshot to %s", path)


def load_membership(cache_dir: Path) -> dict[str, list[str]]:
    """Load previous membership snapshot. Returns empty dict if not found."""
    path = cache_dir / "membership.json"
    if not path.exists():
        return {}
    with open(path) as f:
        result: dict[str, list[str]] = json.load(f)
        return result


