def extraction_signature(config: Config) -> str:
    """Hash of every setting that changes PDF extraction output.

    Stored in card _meta and compared on cache load, so switching the PDF
    backend (or any extraction knob) invalidates cached cards automatically
    instead of requiring a manual prompt_version bump.
    """
    payload = {
        "backend": config.extraction.backend,
        "mode": config.extraction.mode,
        "target_sections": config.extraction.target_sections,
        "fuzzy_threshold": config.extraction.fuzzy_threshold,
        "max_first_pages": config.max_first_pages,
        "max_last_pages": config.max_last_pages,
        "max_text_chars": config.max_text_chars,
        "max_pdf_pages": config.max_pdf_pages,
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def save_card(card: PaperCard, config: Config, cards_dir: Path) -> None:
    """Save a single paper card to the cache with provenance metadata."""
    llm_config = config.llm.config_for_stage("cards")
    data = card.model_dump()
    data["_meta"] = {
        "model": llm_config.model,
        "prompt_version": config.prompt_version,
        "extraction_signature": extraction_signature(config),
        "generated_at": datetime.now(UTC).isoformat(),
    }
    fp = cards_dir / f"{card.citekey}.json"
    fp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")


def load_cached_cards(cache_dir: Path) -> dict[str, PaperCard]:
    """Load all cached paper cards from disk."""
    cards_dir = cache_dir / "cards"
    if not cards_dir.exists():
        return {}

    cards: dict[str, PaperCard] = {}
    for filepath in cards_dir.glob("*.json"):
        try:
            data = json.loads(filepath.read_text(encoding="utf-8"))
            data.pop("_meta", None)
            card = PaperCard(**data)
            cards[card.citekey] = card
        except Exception as e:
            logger.warning("Failed to load card %s: %s", filepath.name, e)
    return cards


def iter_version_matched_cards(
    cards_dir: Path,
    prompt_version: int,
    extraction_signature: str | None = None,
) -> Iterator[tuple[Path, dict]]:
    """Yield (filepath, data_dict) for cached card files matching the given prompt_version.

    Iterates over *.json in cards_dir, parses each file, and yields entries
    whose _meta.prompt_version equals prompt_version. When extraction_signature
    is given, _meta.extraction_signature must match as well (cards saved before
    signatures existed never match, and are regenerated). Files that fail to
    parse or have a mismatched version are silently skipped (with a warning log).
    """
    if not cards_dir.exists():
        return

    for filepath in cards_dir.glob("*.json"):
        try:
            data = json.loads(filepath.read_text(encoding="utf-8"))
            meta = data.get("_meta", {})
            if meta.get("prompt_version", 0) != prompt_version:
                continue
            if (
                extraction_signature is not None
                and meta.get("extraction_signature") != extraction_signature
            ):
                continue
            if not data.get("citekey"):
                logger.warning("Card %s has missing or empty citekey", filepath.name)
            yield filepath, data
        except (json.JSONDecodeError, KeyError, ValueError, OSError) as e:
            logger.warning("Failed to read card %s: %s", filepath.name, e)


def load_version_matched_citekeys(
    cache_dir: Path,
    prompt_version: int,
    extraction_signature: str | None = None,
) -> set[str]:
    """Return citekeys of cached cards whose _meta.prompt_version (and, when
    given, _meta.extraction_signature) matches."""
    matched: set[str] = set()
    for _filepath, data in iter_version_matched_cards(
        cache_dir / "cards", prompt_version, extraction_signature
    ):
        citekey = data.get("citekey")
        if citekey:
            matched.add(citekey)
    return matched


