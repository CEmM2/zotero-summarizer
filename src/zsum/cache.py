def _json_compatible(value: Any) -> Any:
    """Return a JSON-serialisable form of *value*."""
    if is_dataclass(value) and not isinstance(value, type):
        return _json_compatible(asdict(value))
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, dict):
        return {str(key): _json_compatible(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_compatible(item) for item in value]
    return value


def save_nlm_mappings(mappings: dict[str, list[Any]], cache_dir: Path) -> None:
    """Persist NotebookLM notebook/source mappings to cache/nlm_notebooks.json."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    path = cache_dir / "nlm_notebooks.json"
    payload = {
        "generated_at": datetime.now(UTC).isoformat(),
        "collections": {
            key: [_json_compatible(mapping) for mapping in value]
            for key, value in sorted(mappings.items())
        },
    }
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info("Saved NotebookLM mappings to %s", path)


def load_nlm_mappings(cache_dir: Path) -> dict[str, list[dict[str, Any]]]:
    """Load NotebookLM mappings from cache/nlm_notebooks.json."""
    path = cache_dir / "nlm_notebooks.json"
    if not path.exists():
        return {}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        logger.warning("Failed to read NotebookLM mappings cache: %s", e)
        return {}

    raw_collections = payload.get("collections", payload)
    if not isinstance(raw_collections, dict):
        logger.warning("NotebookLM mappings cache has invalid structure: %s", path)
        return {}

    result: dict[str, list[dict[str, Any]]] = {}
    for key, mappings in raw_collections.items():
        if not isinstance(key, str) or not isinstance(mappings, list):
            continue
        cleaned = [mapping for mapping in mappings if isinstance(mapping, dict)]
        result[key] = cleaned
    return result


def clear_nlm_mappings(cache_dir: Path) -> None:
    """Remove the NotebookLM mappings cache file if it exists."""
    path = cache_dir / "nlm_notebooks.json"
    if path.exists():
        path.unlink()
        logger.info("Removed NotebookLM mappings cache %s", path)


