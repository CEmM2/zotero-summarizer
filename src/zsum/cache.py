def save_citations(records: dict[str, CitationRecord], cache_dir: Path) -> None:
    """Persist citation records to cache/citations.json."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    data = {ck: rec.model_dump() for ck, rec in records.items()}
    path = cache_dir / "citations.json"
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")


def load_citations(cache_dir: Path) -> dict[str, CitationRecord]:
    """Load citation records from cache/citations.json; returns empty dict if absent."""
    path = cache_dir / "citations.json"
    if not path.exists():
        return {}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        logger.warning("Failed to read citations cache: %s", e)
        return {}
    result: dict[str, CitationRecord] = {}
    for ck, payload in raw.items():
        try:
            result[ck] = CitationRecord(**payload)
        except Exception as e:
            logger.warning("Bad citation record for %s: %s", ck, e)
    return result


