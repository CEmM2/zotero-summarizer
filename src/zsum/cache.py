# Plugin index (index.json consumed by the Obsidian plugin)
# ---------------------------------------------------------------------------


def save_plugin_index(idx: LibraryIndex, cache_dir: Path, config: Config | None = None) -> None:
    """Write cache/index.json summarising card and digest states for the Obsidian plugin."""
    cards_dir = cache_dir / "cards"
    digests_dir = cache_dir / "digests"
    citations = load_citations(cache_dir)
    expected_extraction_method = (
        "notebooklm" if config is not None and config.extraction.mode == "notebooklm" else None
    )
    notebooklm_digest_keys = (
        load_nlm_digest_keys(cache_dir) if expected_extraction_method == "notebooklm" else None
    )
    notebooklm_redigest_keys = (
        load_nlm_redigest_keys(cache_dir) if expected_extraction_method == "notebooklm" else None
    )

    # Collect cached citekeys, text_quality, and paper_type from card JSON files.
    cached_quality: dict[str, str] = {}
    cached_paper_type: dict[str, str] = {}
    cached_extraction_method: dict[str, str] = {}
    if cards_dir.exists():
        for fp in cards_dir.glob("*.json"):
            try:
                data = json.loads(fp.read_text(encoding="utf-8"))
                data.pop("_meta", None)
                citekey = data.get("citekey") or fp.stem
                extraction_method = data.get("extraction_method")
                if (
                    expected_extraction_method is not None
                    and extraction_method != expected_extraction_method
                    and extraction_method != "fallback_pages"
                ):
                    continue
                cached_quality[citekey] = data.get("text_quality", "good")
                if data.get("paper_type"):
                    cached_paper_type[citekey] = data["paper_type"]
                if isinstance(extraction_method, str) and extraction_method:
                    cached_extraction_method[citekey] = extraction_method
            except Exception:
                pass

    # Build inverted membership map: citekey → [collection_key, ...]
    item_collections: dict[str, list[str]] = {ck: [] for ck in idx.items}
    for col_key, col in idx.collections.items():
        for ck in col.item_citekeys:
            if ck in item_collections:
                item_collections[ck].append(col_key)

    # Serialise items.
    items_out: dict[str, dict] = {}
    for citekey, item in idx.items.items():
        if citekey in cached_quality:
            if cached_extraction_method.get(citekey) == "fallback_pages":
                card_state = "fallback"
            elif cached_quality[citekey] == "degraded":
                card_state = "degraded"
            else:
                card_state = "cached"
        elif item.has_pdf:
            card_state = "pending"
        else:
            card_state = "no_pdf"

        paper_type = cached_paper_type.get(citekey, item.paper_type or "research")
        item_out: dict[str, Any] = {
            "citekey": citekey,
            "year": item.year or 0,
            "venue": item.venue or "",
            "collections": item_collections.get(citekey, []),
            "card_state": card_state,
            "paper_type": paper_type,
        }
        rec = citations.get(citekey)
        if rec and rec.citation_count is not None:
            item_out["citation_count"] = rec.citation_count
        if citekey in cached_extraction_method:
            item_out["extraction_method"] = cached_extraction_method[citekey]
        items_out[citekey] = item_out

    # Serialise collections.
    collections_out: dict[str, dict] = {}
    for col_key, col in idx.collections.items():
        digest_file = digests_dir / f"{col_key}.md"
        if (
            notebooklm_digest_keys is not None and col_key not in notebooklm_digest_keys
        ) or not digest_file.exists():
            digest_state = "missing"
        elif any_card_content_changed(
            col_key,
            col.item_citekeys,
            cards_dir,
            digests_dir,
            expected_extraction_method=expected_extraction_method,
        ):
            digest_state = "stale"
        else:
            digest_state = "ok"

        collections_out[col_key] = {
            "name": col.name,
            "parent": col.parent_key,
            "path": col.path,
            "item_count": len(col.item_citekeys),
            "digest_state": digest_state,
            "redigest_state": (
                redigest_state_for_collection(col_key, cache_dir, config)
                if notebooklm_redigest_keys is None or col_key in notebooklm_redigest_keys
                else "missing"
            ),
        }

    plugin_index = {
        "generated_at": datetime.now(UTC).isoformat(),
        "collections": collections_out,
        "items": items_out,
    }

    cache_dir.mkdir(parents=True, exist_ok=True)
    out = cache_dir / "index.json"
    out.write_text(json.dumps(plugin_index, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info("Saved plugin index to %s", out)
