def card_content_hash(card_path: Path) -> str:
    """Compute SHA-256 of a card's content fields (excluding _meta)."""
    data = json.loads(card_path.read_text(encoding="utf-8"))
    data.pop("_meta", None)
    canonical = json.dumps(data, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def card_extraction_method(card_path: Path) -> str | None:
    """Return a cached card's extraction_method, if present and readable."""
    try:
        data = json.loads(card_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    value = data.get("extraction_method")
    return value if isinstance(value, str) and value else None


def save_digest_hashes(
    col_key: str,
    citekeys: list[str],
    cards_dir: Path,
    digests_dir: Path,
) -> None:
    """Save content hashes for all cards used in a digest."""
    hashes: dict[str, str] = {}
    for ck in sorted(citekeys):
        card_path = cards_dir / f"{ck}.json"
        if card_path.exists():
            hashes[ck] = card_content_hash(card_path)
    hash_file = digests_dir / f"{col_key}_hashes.json"
    hash_file.write_text(json.dumps(hashes, indent=2), encoding="utf-8")


def any_card_content_changed(
    col_key: str,
    citekeys: list[str],
    cards_dir: Path,
    digests_dir: Path,
    *,
    expected_extraction_method: str | None = None,
) -> bool:
    """Return True if any card's content has changed since the digest was generated."""
    hash_file = digests_dir / f"{col_key}_hashes.json"
    if not hash_file.exists():
        return True  # no hashes recorded, treat as stale

    saved_hashes: dict[str, str] = json.loads(hash_file.read_text(encoding="utf-8"))

    for ck in citekeys:
        card_path = cards_dir / f"{ck}.json"
        if not card_path.exists():
            continue
        if expected_extraction_method is not None:
            current_method = card_extraction_method(card_path)
            if current_method != expected_extraction_method:
                continue
        if saved_hashes.get(ck) != card_content_hash(card_path):
            return True

    return False


def load_cached_digests(cache_dir: Path) -> dict[str, str]:
    """Load all cached collection digests from disk."""
    digests_dir = cache_dir / "digests"
    if not digests_dir.exists():
        return {}

    digests: dict[str, str] = {}
    for filepath in digests_dir.glob("*.md"):
        key = filepath.stem
        digests[key] = filepath.read_text(encoding="utf-8")
    return digests


def digest_content_hash(text: str) -> str:
    """Compute a stable SHA-256 for digest markdown content."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def save_redigest(
    col_key: str,
    redigest: str,
    source_digest: str,
    cache_dir: Path,
    config: Config,
) -> None:
    """Persist a redigest markdown file plus its source-digest metadata."""
    redigests_dir = cache_dir / "redigests"
    redigests_dir.mkdir(parents=True, exist_ok=True)
    redigest_path = redigests_dir / f"{col_key}.md"
    metadata_path = redigests_dir / f"{col_key}.json"
    provider = config.llm.provider_for_stage("redigest")
    llm_config = config.llm.config_for_stage("redigest")

    redigest_path.write_text(redigest, encoding="utf-8")
    metadata = {
        "source_digest_hash": digest_content_hash(source_digest),
        "provider": provider,
        "model": getattr(llm_config, "model", ""),
        "generated_at": datetime.now(UTC).isoformat(),
    }
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")


def load_cached_redigests(cache_dir: Path) -> dict[str, str]:
    """Load all cached redigest markdown files from disk."""
    redigests_dir = cache_dir / "redigests"
    if not redigests_dir.exists():
        return {}

    redigests: dict[str, str] = {}
    for filepath in redigests_dir.glob("*.md"):
        redigests[filepath.stem] = filepath.read_text(encoding="utf-8")
    return redigests


def load_redigest_metadata(cache_dir: Path, col_key: str) -> dict[str, Any] | None:
    """Load a redigest metadata sidecar if present and valid JSON."""
    metadata_path = cache_dir / "redigests" / f"{col_key}.json"
    if not metadata_path.exists():
        return None
    try:
        data: dict[str, Any] = json.loads(metadata_path.read_text(encoding="utf-8"))
        return data
    except (json.JSONDecodeError, OSError) as e:
        logger.warning("Failed to read redigest metadata for %s: %s", col_key, e)
        return None


def redigest_state_for_collection(
    col_key: str, cache_dir: Path, config: Config | None = None
) -> str:
    """Return `ok`, `stale`, or `missing` for a collection redigest.

    When *config* is provided the cached provider/model are compared against the
    current configuration — a model change makes the redigest ``stale`` even if
    the source digest hasn't changed.
    """
    digests_dir = cache_dir / "digests"
    redigests_dir = cache_dir / "redigests"
    digest_path = digests_dir / f"{col_key}.md"
    redigest_path = redigests_dir / f"{col_key}.md"
    metadata = load_redigest_metadata(cache_dir, col_key)

    if not redigest_path.exists() or metadata is None:
        return "missing"
    if not digest_path.exists():
        return "stale"

    current_hash = digest_content_hash(digest_path.read_text(encoding="utf-8"))
    if metadata.get("source_digest_hash") != current_hash:
        return "stale"

    # Detect provider/model change since last redigest
    if config is not None:
        cur_provider = config.llm.provider_for_stage("redigest")
        cur_model = getattr(config.llm.config_for_stage("redigest"), "model", "")
        if metadata.get("provider") != cur_provider or metadata.get("model") != cur_model:
            logger.info(
                "Redigest model changed for %s: %s/%s → %s/%s — marking stale",
                col_key,
                metadata.get("provider"),
                metadata.get("model"),
                cur_provider,
                cur_model,
            )
            return "stale"

    return "ok"


def load_effective_digests(
    cache_dir: Path,
    collection_keys: set[str] | None = None,
    redigest_keys: set[str] | None = None,
) -> dict[str, str]:
    """Load publish-ready digests, preferring fresh redigests over first-pass digests."""
    first_pass = load_cached_digests(cache_dir)
    if collection_keys is not None:
        first_pass = {key: value for key, value in first_pass.items() if key in collection_keys}
    redigests = load_cached_redigests(cache_dir)
    effective = dict(first_pass)
    for col_key in first_pass:
        if redigest_keys is not None and col_key not in redigest_keys:
            continue
        if redigest_state_for_collection(col_key, cache_dir) == "ok" and col_key in redigests:
            effective[col_key] = redigests[col_key]
    return effective


